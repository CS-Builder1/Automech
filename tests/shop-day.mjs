const errors = []
page.on('pageerror', error => errors.push(error.message))
const button = name => page.getByRole('button', { name, exact: true })
const link = name => page.getByRole('link', { name, exact: true })
const heading = name => page.getByRole('heading', { name, exact: true })
const input = name => page.getByLabel(name, { exact: true })
const dialog = page.getByRole('dialog')
const owner = 'Jules James'
const plate = 'LC-279'
const successVIN = '1HGCM82633A004352'
const unavailableVIN = '1HGCM82633A004353'
let decoded = 0
let unavailable = 0

await context.route('https://vpic.nhtsa.dot.gov/**', async route => {
  if (route.request().url().includes(successVIN)) {
    decoded++
    await route.fulfill({ json: { Results: [{ Make: 'Honda', Model: 'Accord', ModelYear: '2003', VehicleType: 'Car' }] },
      headers: { 'access-control-allow-origin': '*' } })
  } else if (route.request().url().includes(unavailableVIN)) {
    unavailable++
    await route.abort('internetdisconnected')
  } else throw new Error('Unexpected VIN request: ' + route.request().url())
})

async function approve(revision, total, method) {
  await button(revision === 1 ? 'Capture approval' : 'Update').click()
  await dialog.getByText('Brake service', { exact: false }).first().waitFor()
  await dialog.getByText('Brake pad kit', { exact: false }).first().waitFor()
  await dialog.getByText(new RegExp('Authorized total.*' + total + '\\.00')).waitFor()
  await dialog.getByLabel('Authorized by').fill(owner)
  await dialog.getByLabel('How was it authorized?').selectOption(method)
  const submit = dialog.getByRole('button', { name: 'Record approval' })
  if (method === 'signature') {
    assert.equal(await submit.isDisabled(), true)
    const canvas = dialog.locator('canvas')
    await canvas.scrollIntoViewIfNeeded()
    const rect = await canvas.boundingBox()
    assert.ok(rect)
    await page.mouse.move(rect.x + 12, rect.y + 15)
    await page.mouse.down()
    await page.mouse.move(rect.x + 80, rect.y + 37, { steps: 6 })
    await page.mouse.move(rect.x + 110, rect.y + 20, { steps: 4 })
    await page.mouse.up()
  }
  await submit.click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByText(new RegExp('Approval ' + revision + '.*' + total + '\\.00')).waitFor()
}

