import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const base = process.env.APP_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium' })
try {
  const page = await browser.newPage()
  page.setDefaultTimeout(4000)
  const button = (name) => page.getByRole('button', { name, exact: true })
  await page.goto(base + '/customers/new')
  await page.locator('#firstName').fill('Alex')
  await page.locator('#lastName').fill('Stone')
  await page.locator('#phone').fill('(555) 123-4567')
  await button('Create customer').click()
  await page.getByRole('heading', { name: 'Alex Stone' }).waitFor()
  const customer = page.url()
  await page.getByRole('link', {name: /add vehicle/i}).click()
  for (const [id, value] of Object.entries({plate:'FR-12', make:'Toyota', model:'Corolla', vin:'1HGCM82633A004352', mileage:'35,000'}))
    await page.locator('#' + id).fill(value)
  await button('Add vehicle').click()
  await page.goto(customer)
  await page.getByRole('link', {name: /Start job/i}).click()
  await page.locator('#complaint').fill('Brake shudder')
  await page.locator('#mileage').fill('40,012')
  await button('Create estimate').click()
  await page.getByRole('heading', {name:'RO-1001'}).waitFor()
  const job = page.url()
  await page.goto(base + '/customers')
  for (const query of ['Alex Stone', '5551234567', 'fr12', '1hgcm82633a004352', 'RO1001']) {
    await page.getByRole('searchbox').fill(query)
    await page.getByRole('link', {name:/Alex Stone/}).waitFor()
  }
  await page.goto(base + '/search?type=vehicles')
  await page.getByRole('searchbox').fill('fr12')
  await page.getByRole('link',{name:/^Toyota Corolla/}).click()
  await page.getByRole('heading', {name:'Toyota Corolla'}).waitFor()
  assert.match(await page.getByRole('link', {name:/RO-1001/}).innerText(), /Brake shudder/)
  assert.match(await page.getByRole('link', {name:/RO-1001/}).innerText(), /40,012/)
  await page.goto(base + '/jobs')
  await page.getByRole('searchbox').fill('ro1001')
  assert.equal(await page.getByRole('link', {name:/RO-1001/}).getAttribute('href'), new URL(job).pathname)
  await page.goto(customer)
  page.once('dialog', d => d.accept())
  await button('Archive customer').click()
  await button('Restore customer').waitFor()
  await page.goto(base + '/search?type=vehicles')
  await page.getByRole('heading', {name:'No records found'}).waitFor()
  assert.equal(await page.getByRole('link',{name:/^Toyota Corolla/}).count(), 0)
  await page.goto(base + '/customers')
  await page.getByLabel('Show archived').check()
  await page.getByRole('link',{name:/Alex Stone/}).click()
  await page.getByRole('link',{name:/^Toyota Corolla/}).click()
  await page.getByText(/archived/i).first().waitFor()
  assert.equal(await page.getByRole('link',{name:/Edit vehicle/}).count(), 0)
  await page.goto(customer)
  await button('Restore customer').click()
  await page.goto(base + '/search?type=vehicles')
  await page.getByRole('link',{name:/^Toyota Corolla/}).waitFor()
  console.log('Customer, vehicle and RO lookup, per-vehicle history, archive and restore verified.')
} finally {
  await browser.close()
}
